#!/usr/bin/env node
import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import * as core from '../core.js';

function usage() {
  return 'Usage: node tools/generate-runtime-corpus.mjs --problems FILE --contests FILE --output FILE [--write]';
}
function option(args, name) {
  const index = args.indexOf(name);
  return index >= 0 ? args[index + 1] : null;
}
function readProblems(value) {
  const records = Array.isArray(value) ? value : value?.result?.problems;
  if (!Array.isArray(records)) throw new Error('Problem snapshot must contain a Codeforces result.problems array');
  return records
    .filter(core.isEligibleProblem)
    .map(({ contestId, index, name, type, rating, tags }) => ({ contestId, index, name, type, rating, tags: Array.isArray(tags) ? tags : [] }))
    .sort((a, b) => core.stableProblemId(a).localeCompare(core.stableProblemId(b)));
}
function readContests(value) {
  const records = Array.isArray(value) ? value : value?.result;
  if (!Array.isArray(records)) throw new Error('Contest snapshot must contain a result array');
  return records
    .filter((contest) => Number.isInteger(Number(contest?.id)) && Number.isFinite(contest?.startTimeSeconds) && Number.isFinite(contest?.durationSeconds))
    .map(({ id, startTimeSeconds, durationSeconds }) => ({ id, startTimeSeconds, durationSeconds }))
    .sort((a, b) => Number(a.id) - Number(b.id));
}
function sha256(buffer) { return crypto.createHash('sha256').update(buffer).digest('hex'); }

const args = process.argv.slice(2);
if (args.includes('--help') || !args.length) {
  console.log(usage());
  process.exit(args.length ? 0 : 1);
}
const problemsPath = option(args, '--problems');
const contestsPath = option(args, '--contests');
const output = option(args, '--output');
if (!problemsPath || !contestsPath || !output) throw new Error(usage());
const [problemBytes, contestBytes] = await Promise.all([fs.readFile(problemsPath), fs.readFile(contestsPath)]);
const problems = readProblems(JSON.parse(problemBytes));
const contests = readContests(JSON.parse(contestBytes));
if (!problems.length || !contests.length) throw new Error('Runtime corpus cannot be empty');
const corpus = {
  schema: 'accept-runtime-corpus-v1',
  sourceProvenance: { problemsSha256: sha256(problemBytes), contestsSha256: sha256(contestBytes) },
  problems,
  contests,
};
const source = `// Generated by tools/generate-runtime-corpus.mjs from pinned snapshots.\nexport const RUNTIME_CORPUS = Object.freeze(${JSON.stringify(corpus)});\n`;
const report = {
  output,
  problems: problems.length,
  contests: contests.length,
  problemsSha256: corpus.sourceProvenance.problemsSha256,
  contestsSha256: corpus.sourceProvenance.contestsSha256,
  writeRequested: args.includes('--write'),
};
if (args.includes('--write')) {
  await fs.mkdir(path.dirname(output), { recursive: true });
  const temporary = `${output}.tmp-${process.pid}`;
  await fs.writeFile(temporary, source, 'utf8');
  await fs.rename(temporary, output);
  console.log(JSON.stringify({ ...report, written: output }, null, 2));
} else {
  console.log(JSON.stringify(report, null, 2));
}
