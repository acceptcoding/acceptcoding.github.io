#!/usr/bin/env node
import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import path from 'node:path';
import * as core from '../core.js';

function usage() {
  return `Usage: node tools/generate-canonical-history.mjs --problems FILE --contests FILE --start YYYY-MM-DD --end YYYY-MM-DD --output FILE [--write]\n\nReads pinned JSON snapshots, validates every date, and prints a report by default.\n--write is required before replacing the explicitly supplied output path.`;
}
function option(args, name) {
  const index = args.indexOf(name);
  return index >= 0 ? args[index + 1] : null;
}
function readPayload(value, label) {
  if (Array.isArray(value)) return value;
  if (Array.isArray(value?.result)) return value.result;
  if (Array.isArray(value?.result?.problems)) return value.result.problems;
  if (Array.isArray(value?.problems)) return value.problems;
  throw new Error(`${label} snapshot must contain an array or Codeforces result array`);
}
function sha256(buffer) {
  return crypto.createHash('sha256').update(buffer).digest('hex');
}
function datesBetween(start, end) {
  const dates = [];
  for (let date = start; date <= end; date = core.shiftDate(date, 1)) dates.push(date);
  return dates;
}
function manifestSource({ start, end, problemHash, contestHash, entries }) {
  const manifest = {
    schema: core.CANONICAL_HISTORY_SCHEMA,
    manifestRevision: `backfill-${problemHash.slice(0, 12)}-${contestHash.slice(0, 12)}-${start}-${end}`,
    resolverVersion: core.SELECTOR_VERSION,
    selectionSalt: core.SITE_SALT,
    boundary: 'utc-midnight-completion',
    coverageStart: start,
    coverageEnd: end,
    sourceProvenance: { problemsSha256: problemHash, contestsSha256: contestHash },
    entries,
  };
  return `// Generated by tools/generate-canonical-history.mjs from pinned snapshots.\nexport const CANONICAL_HISTORY_MANIFEST = Object.freeze(${JSON.stringify(manifest, null, 2)});\n`;
}

const args = process.argv.slice(2);
if (args.includes('--help') || !args.length) {
  console.log(usage());
  process.exit(args.length ? 0 : 1);
}
const problemsPath = option(args, '--problems');
const contestsPath = option(args, '--contests');
const start = option(args, '--start');
const end = option(args, '--end');
const output = option(args, '--output');
if (!problemsPath || !contestsPath || !start || !end || !output) throw new Error(usage());
if (!core.isValidDateString(start) || !core.isValidDateString(end) || start > end || start < core.LAUNCH_DATE) throw new Error('Invalid canonical date range');

const [problemBytes, contestBytes] = await Promise.all([fs.readFile(problemsPath), fs.readFile(contestsPath)]);
const problems = readPayload(JSON.parse(problemBytes), 'Problem');
const contests = readPayload(JSON.parse(contestBytes), 'Contest');
const entries = {};
const failures = [];
for (const date of datesBetween(start, end)) {
  try {
    const eligible = core.filterHistoricalProblems(problems, contests, date, end);
    const ladder = await core.buildLadder(eligible, date, core.SITE_SALT, end);
    const ids = ladder.map(core.stableProblemId);
    if (ids.length !== core.LADDER_SIZE || new Set(ids).size !== core.LADDER_SIZE) throw new Error('daily ladder is not thirteen distinct IDs');
    entries[date] = { ids };
  } catch (error) {
    failures.push({ date, reason: error instanceof Error ? error.message : String(error) });
  }
}
const report = {
  start,
  end,
  datesAttempted: datesBetween(start, end).length,
  datesValid: Object.keys(entries).length,
  failures,
  problemsSha256: sha256(problemBytes),
  contestsSha256: sha256(contestBytes),
  output,
  writeRequested: args.includes('--write'),
};
if (failures.length) {
  console.error(JSON.stringify(report, null, 2));
  process.exitCode = 2;
} else if (args.includes('--write')) {
  const source = manifestSource({ start, end, problemHash: report.problemsSha256, contestHash: report.contestsSha256, entries });
  const temporary = `${output}.tmp-${process.pid}`;
  await fs.mkdir(path.dirname(output), { recursive: true });
  await fs.writeFile(temporary, source, 'utf8');
  await fs.rename(temporary, output);
  console.log(JSON.stringify({ ...report, written: output }, null, 2));
} else {
  console.log(JSON.stringify(report, null, 2));
}
